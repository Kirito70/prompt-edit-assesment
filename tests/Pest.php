/**
 * Point the app at a fake Pixelforge. Pass extra stubs (or a replacement for
 * the pricing stub) keyed by URL.
 *
 * @param  array<string, mixed>  $stubs
 */
function fakePixelForge(array $stubs = []): void
{
    config([
        'services.pixelforge.base_url' => 'https://pixelforge.test/v1',
        'services.pixelforge.api_key' => 'pf_test_key',
        'services.pixelforge.timeout' => 5,
    ]);

    Cache::flush();

    // A fresh factory, so these stubs replace any registered earlier in the test.
    Http::swap(new HttpFactory);
    Http::fake(array_merge([
        'https://pixelforge.test/v1/pricing' => Http::response(pfFixturePricing()),
    ], $stubs));
}

/**
 * A finished, billed generation: what the admin report sums.
 */
function completedGeneration(User $user, string $charge, string $cost, string $at, array $extra = []): Generation
{
    $time = Carbon::parse($at, 'UTC');

    return Generation::factory()->for($user)->succeeded()->create(array_merge([
        'customer_charge' => $charge,
        'provider_cost' => $cost,
        'provider_completed_at' => $time,
        'settled_at' => $time,
    ], $extra));
}
